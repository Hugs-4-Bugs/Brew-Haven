package com.inn.cafe.Utils;

import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.mail.SimpleMailMessage;
import org.springframework.mail.javamail.JavaMailSender;
import org.springframework.mail.javamail.MimeMessageHelper;
import org.springframework.stereotype.Service;

import javax.mail.MessagingException;
import javax.mail.internet.MimeMessage;
import java.util.List;

/**
 * Email helper (FIX A.7: sender address externalized to configuration instead of a
 * hardcoded personal Gmail account).
 *
 * forgotMail now receives a ONE-TIME TEMPORARY password generated by UserServiceImpl
 * (FIX A.3) — it never mails stored password hashes anymore.
 */
@Service
public class EmailUtils {

    @Autowired
    private JavaMailSender emailSender;

    @Value("${cafe.mail.from:${spring.mail.username:noreply@cafemgt.local}}")
    private String fromAddress;

    public void sendSimpleMessage(String to, String subject, String text, List<String> list) {
        SimpleMailMessage message = new SimpleMailMessage();
        message.setFrom(fromAddress);
        message.setTo(to);
        message.setSubject(subject);
        message.setText(text);
        if (list != null && !list.isEmpty()) {
            message.setCc(getCcArray(list));
        }
        emailSender.send(message);
    }

    private String[] getCcArray(List<String> ccList) {
        return ccList.toArray(new String[0]);
    }

    /**
     * Sends the user their login email together with a one-time temporary password.
     * NOTE: requires a working SMTP configuration (spring.mail.*). Mail failures are
     * propagated to the caller so the API can respond honestly.
     */
    public void forgotMail(String to, String subject, String tempPassword) throws MessagingException {
        MimeMessage message = emailSender.createMimeMessage();
        MimeMessageHelper helper = new MimeMessageHelper(message, true);
        helper.setFrom(fromAddress);
        helper.setTo(to);
        message.setSubject(subject);
        String htmlMsg = "<p><b>Your temporary login details for Cafe Management System</b><br>"
                + "<b>Email: </b> " + to + " <br><b>Temporary Password: </b> " + tempPassword
                + "<br>Please log in and change your password immediately.</p>";
        message.setContent(htmlMsg, "text/html");
        emailSender.send(message);
    }
}
