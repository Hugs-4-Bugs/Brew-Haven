import { useCallback, useEffect, useMemo, useState } from 'react';
import * as api from '../api/cafe';
import { useAuth } from '../auth/useAuth';
import { Button, Card, EmptyState, ErrorState, LoadingState, Modal, ToastStack, useEntrance, useToasts } from '../components/ui';
import { downloadBlob, formatMoney, parseBillLines } from '../utils/format';

export default function BillsPage(): JSX.Element {
  const { isAdmin } = useAuth();
  const { toasts, push, dismiss } = useToasts();
  const [bills, setBills] = useState<api.Bill[] | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [detail, setDetail] = useState<api.Bill | null>(null);
  const [confirmDelete, setConfirmDelete] = useState<api.Bill | null>(null);
  const [busy, setBusy] = useState(false);

  const load = useCallback(async () => {
    setError(null);
    try {
      setBills(await api.getBills()); // admin: all bills; user: own bills (backend contract)
    } catch (err) {
      setError(err instanceof Error ? err.message : 'Failed to load bills.');
    }
  }, []);

  useEffect(() => {
    void load();
  }, [load]);

  useEntrance('.card, table.data tr', [bills?.length]);

  const stats = useMemo(() => {
    const list = bills ?? [];
    const revenue = list.reduce((s, b) => s + (b.total ?? 0), 0);
    return { count: list.length, revenue };
  }, [bills]);

  const downloadPdf = async (bill: api.Bill): Promise<void> => {
    setBusy(true);
    try {
      const blob = await api.downloadBillPdf(bill.uuid);
      downloadBlob(blob, `${bill.uuid}.pdf`);
    } catch (err) {
      push('err', err instanceof Error ? err.message : 'PDF download failed.');
    } finally {
      setBusy(false);
    }
  };

  const doDelete = async (): Promise<void> => {
    if (!confirmDelete) return;
    setBusy(true);
    try {
      const message = await api.deleteBill(confirmDelete.id);
      push('ok', message);
      setConfirmDelete(null);
      await load();
    } catch (err) {
      // non-admin receives 401 "Unauthorized access" (backend admin-only contract)
      push('err', err instanceof Error ? err.message : 'Delete failed.');
    } finally {
      setBusy(false);
    }
  };

  if (error) return <ErrorState message={error} onRetry={load} />;

  return (
    <>
      <div className="stat-grid">
        <div className="card stat-card">
          <div className="stat-ico" aria-hidden="true">🧾</div>
          <div className="stat-value">{stats.count}</div>
          <div className="stat-label">Bills {isAdmin ? '(all users)' : '(generated by you)'}</div>
        </div>
        <div className="card stat-card">
          <div className="stat-ico" aria-hidden="true">💰</div>
          <div className="stat-value">{formatMoney(stats.revenue)}</div>
          <div className="stat-label">Total billed</div>
        </div>
      </div>

      {!bills ? (
        <LoadingState label="Loading bills…" />
      ) : bills.length === 0 ? (
        <Card>
          <EmptyState ico="📄" title="No bills yet" hint="Generate the first bill from the POS screen." />
        </Card>
      ) : (
        <div className="table-wrap">
          <table className="data">
            <thead>
              <tr>
                <th>Bill</th>
                <th>Customer</th>
                <th>Payment</th>
                <th>Total</th>
                <th style={{ width: 230 }}>Actions</th>
              </tr>
            </thead>
            <tbody>
              {bills.map((b) => (
                <tr key={b.id}>
                  <td className="mono">{b.uuid}</td>
                  <td>
                    <strong>{b.name}</strong>
                    <div className="muted">{b.email}</div>
                  </td>
                  <td>
                    <span className="badge badge-warn">{b.paymentMethod}</span>
                  </td>
                  <td><strong>{formatMoney(b.total)}</strong></td>
                  <td>
                    <div className="row">
                      <Button size="sm" onClick={() => setDetail(b)}>View</Button>
                      <Button size="sm" variant="primary" onClick={() => void downloadPdf(b)} loading={busy}>PDF</Button>
                      {isAdmin && <Button size="sm" variant="danger" onClick={() => setConfirmDelete(b)}>Delete</Button>}
                    </div>
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      )}

      {detail && (
        <Modal title={`Bill ${detail.uuid}`} onClose={() => setDetail(null)}>
          <p style={{ margin: '0 0 10px' }}>
            <strong>{detail.name}</strong> · {detail.contactNumber} · {detail.email}
          </p>
          <div className="table-wrap">
            <table className="data" style={{ minWidth: 380 }}>
              <thead>
                <tr>
                  <th>Item</th>
                  <th>Qty</th>
                  <th>Price</th>
                  <th>Total</th>
                </tr>
              </thead>
              <tbody>
                {parseBillLines(detail.productDetails).map((line, i) => (
                  <tr key={i}>
                    <td>{line.name}</td>
                    <td>{line.quantity}</td>
                    <td>{formatMoney(line.price)}</td>
                    <td>{formatMoney(line.total)}</td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
          <div className="spread mt-2">
            <span className="muted">Payment: {detail.paymentMethod}</span>
            <strong style={{ fontSize: 18 }}>Total {formatMoney(detail.total)}</strong>
          </div>
          <div className="modal-actions">
            <Button variant="ghost" onClick={() => setDetail(null)}>Close</Button>
            <Button variant="primary" onClick={() => void downloadPdf(detail)} loading={busy}>Download PDF</Button>
          </div>
        </Modal>
      )}

      {confirmDelete && (
        <Modal title="Delete bill" onClose={() => setConfirmDelete(null)}>
          <p>
            Delete bill <strong>{confirmDelete.uuid}</strong> ({formatMoney(confirmDelete.total)})? This cannot be undone.
          </p>
          <div className="modal-actions">
            <Button variant="ghost" onClick={() => setConfirmDelete(null)}>Cancel</Button>
            <Button variant="danger" onClick={() => void doDelete()} loading={busy}>Delete</Button>
          </div>
        </Modal>
      )}

      <ToastStack toasts={toasts} dismiss={dismiss} />
    </>
  );
}
